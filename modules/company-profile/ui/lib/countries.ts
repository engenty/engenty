export function getCountryName(code: string, locale: "en" | "de"): string {
  const entry = COUNTRIES.find((c) => c.code === code);
  if (!entry) {
    return code;
  }
  if (locale === "de" && COUNTRY_NAME_DE[code]) {
    return COUNTRY_NAME_DE[code];
  }
  return entry.nameEn;
}
